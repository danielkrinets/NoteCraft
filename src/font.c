/* Cyrillic letters that are drawn exactly like a Latin letter. */
static const struct { uint32_t cp, like; } ALIAS[] = {
    {0x0410, 'A'}, {0x0412, 'B'}, {0x0415, 'E'}, {0x041A, 'K'}, {0x041C, 'M'},
    {0x041D, 'H'}, {0x041E, 'O'}, {0x0420, 'P'}, {0x0421, 'C'}, {0x0422, 'T'},
    {0x0425, 'X'}, {0x0430, 'a'}, {0x0435, 'e'}, {0x043E, 'o'}, {0x0440, 'p'},
    {0x0441, 'c'}, {0x0443, 'y'}, {0x0445, 'x'},
};

#define NSRC ((int)(sizeof SRC / sizeof SRC[0]))
#define NALIAS ((int)(sizeof ALIAS / sizeof ALIAS[0]))

static Glyph glyphs[NSRC + NALIAS];
static int nglyphs;
static const Glyph *ascii_idx[128];

static int cmp_glyph(const void *a, const void *b)
{
    uint32_t x = ((const Glyph *)a)->cp, y = ((const Glyph *)b)->cp;
    return x < y ? -1 : x > y;
}

/* Parse one source row table. Returns 0 on success. */
static int parse_glyph(const GSrc *s, Glyph *g)
{
    memset(g, 0, sizeof *g);
    g->cp = s->cp;
    g->top = s->top;
    const char *p = s->rows;
    int w = -1, n = 0;
    while (1) {
        const char *e = strchr(p, '|');
        int len = e ? (int)(e - p) : (int)strlen(p);
        if (w < 0) w = len;
        if (len != w || w > 16 || n >= 9 || s->top + n >= 9) return -1;
        uint16_t bits = 0;
        for (int i = 0; i < len; i++) {
            if (p[i] == '#') bits |= (uint16_t)(0x8000 >> i);
            else if (p[i] != '.') return -1;
        }
        g->rows[n++] = bits;
        if (!e) break;
        p = e + 1;
    }
    g->w = (uint8_t)w;
    g->nrows = (uint8_t)n;
    return 0;
}

static void font_init(void)
{
    if (nglyphs) return;
    for (int i = 0; i < NSRC; i++)
        if (parse_glyph(&SRC[i], &glyphs[nglyphs]) == 0) nglyphs++;
    qsort(glyphs, (size_t)nglyphs, sizeof glyphs[0], cmp_glyph);
    for (int i = 0; i < NALIAS; i++) {
        const Glyph *like = NULL;
        for (int j = 0; j < nglyphs; j++) if (glyphs[j].cp == ALIAS[i].like) like = &glyphs[j];
        if (!like) continue;
        glyphs[nglyphs] = *like;
        glyphs[nglyphs].cp = ALIAS[i].cp;
        nglyphs++;
    }
    qsort(glyphs, (size_t)nglyphs, sizeof glyphs[0], cmp_glyph);
    for (int i = 0; i < nglyphs; i++)
        if (glyphs[i].cp < 128) ascii_idx[glyphs[i].cp] = &glyphs[i];
}

const Glyph *font_glyph(uint32_t cp)
{
    font_init();
    if (cp < 128) return ascii_idx[cp];
    Glyph key; key.cp = cp;
    return bsearch(&key, glyphs, (size_t)nglyphs, sizeof glyphs[0], cmp_glyph);
}

int font_glyph_count(void) { font_init(); return nglyphs; }
const Glyph *font_glyph_at(int i) { font_init(); return (i >= 0 && i < nglyphs) ? &glyphs[i] : NULL; }
int font_has_glyph(uint32_t cp) { return cp == ' ' || cp == 0xA0 || font_glyph(cp) != NULL; }

int font_selftest(void)
{
    Glyph g;
    for (int i = 0; i < NSRC; i++) if (parse_glyph(&SRC[i], &g) != 0) return i + 1;
    return 0;
}

int font_cp_width(uint32_t cp)
{
    if (cp == ' ' || cp == 0xA0) return 4;
    const Glyph *g = font_glyph(cp);
    if (!g) g = font_glyph(0xFFFD);
    return g->w + 1;
}

int font_width(const uint32_t *s, int n)
{
    int w = 0;
    for (int i = 0; i < n; i++) w += font_cp_width(s[i]);
    return w;
}

int font_width_u8(const char *s)
{
    int w = 0;
    size_t n = strlen(s), i = 0;
    while (i < n) {
        uint32_t cp;
        i += (size_t)u8_decode(s + i, n - i, &cp);
        w += font_cp_width(cp);
    }
    return w;
}

int font_draw_cp(Fb *f, int x, int y, uint32_t cp, uint32_t color)
{
    if (cp == ' ' || cp == 0xA0 || cp == '\n') return font_cp_width(cp == '\n' ? ' ' : cp);
    const Glyph *g = font_glyph(cp);
    if (!g) g = font_glyph(0xFFFD);
    for (int r = 0; r < g->nrows; r++) {
        uint16_t bits = g->rows[r];
        if (!bits) continue;
        for (int c = 0; c < g->w; c++)
            if (bits & (0x8000 >> c)) fb_plot(f, x + c, y + g->top + r, color);
    }
    return g->w + 1;
}

void font_draw(Fb *f, int x, int y, const uint32_t *s, int n, uint32_t color)
{
    for (int i = 0; i < n; i++) {
        if (s[i] == '\n') continue;
        x += font_draw_cp(f, x, y, s[i], color);
    }
}

void font_draw_u8(Fb *f, int x, int y, const char *s, uint32_t color, int shadow)
{
    size_t n = strlen(s);
    uint32_t sh = (color & 0xFF000000u) | ((color & 0xFCFCFCu) >> 2);
    for (int pass = shadow ? 0 : 1; pass < 2; pass++) {
        int cx = x + (pass == 0), cy = y + (pass == 0);
        uint32_t col = pass == 0 ? sh : color;
        size_t i = 0;
        while (i < n) {
            uint32_t cp;
            i += (size_t)u8_decode(s + i, n - i, &cp);
            if (cp < 0x20) continue;
            cx += font_draw_cp(f, cx, cy, cp, col);
        }
    }
}

void font_draw_u8_centered(Fb *f, int cx, int y, const char *s, uint32_t color, int shadow)
{
    font_draw_u8(f, cx - font_width_u8(s) / 2, y, s, color, shadow);
}
